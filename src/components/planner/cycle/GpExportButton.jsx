function fmtDate(d) {
  if (!d) return "—";
  const dt = d instanceof Date ? d : new Date(d);
  if (Number.isNaN(dt.getTime())) return "—";
  return dt.toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" });
}

function avgOf(rows, field) {
  const xs = (rows || [])
    .map((r) => Number(r?.[field]))
    .filter((n) => Number.isFinite(n));
  if (xs.length === 0) return null;
  const mean = xs.reduce((a, b) => a + b, 0) / xs.length;
  return Math.round(mean * 10) / 10;
}

function countOf(rows, field, minVal = 1) {
  return (rows || []).filter((r) => {
    const v = Number(r?.[field]);
    return Number.isFinite(v) && v >= minVal;
  }).length;
}

function isWithinWindow(iso, fromISO, toISO) {
  return iso && iso >= fromISO && iso <= toISO;
}

// Safe fetch — returns [] when the entity is missing on base44 (e.g. the
// schema migration hasn't shipped yet) or when the SDK call throws / rejects.
function safeFilter(entityName, args) {
  try {
    const ent = base44?.entities?.[entityName];
    if (!ent || typeof ent.filter !== "function") return Promise.resolve([]);
    return ent.filter(...args).catch(() => []);
  } catch {
    return Promise.resolve([]);
  }
}

// Sprint 6B Feature 2 — exported so MergedExportSheet can build the GP
// PDF alongside the doctor-diary PDF in a single user gesture.
export async function buildSnapshot(profile, plannerConfig) {
  const userId = profile?.user_id;
  if (!userId) return null;
  const today = new Date();
  const from = new Date(today);
  from.setDate(today.getDate() - WINDOW_DAYS);
  const fromISO = from.toISOString().split("T")[0];
  const toISO = today.toISOString().split("T")[0];

  const [dailyAll, menoAll, hrtAll] = await Promise.all([
    safeFilter("DailyCheckins",       [{ user_id: userId }, "-date",       200]),
    safeFilter("MenopauseDailyLog",   [{ user_id: userId }, "-date",       200]),
    safeFilter("HrtLog",              [{ user_id: userId }, "-start_date",  10]),
  ]);

  const daily = (Array.isArray(dailyAll) ? dailyAll : []).filter((r) => isWithinWindow(r?.date, fromISO, toISO));
  const meno = (Array.isArray(menoAll) ? menoAll : []).filter((r) => isWithinWindow(r?.date, fromISO, toISO));
  const hrt = (Array.isArray(hrtAll) ? hrtAll : []).find((r) => r?.is_active !== false) || null;

  return {
    range: { from: fromISO, to: toISO, days: WINDOW_DAYS },
    profile,
    plannerConfig,
    daily,
    meno,
    hrt,
  };
}

// Header/Body/Italic helpers — shared across the three PDF variants.
function pdfHelpers(pdf) {
  const heading = (size) => { pdf.setFont("helvetica", "bold"); pdf.setFontSize(size); };
  const body = (size) => { pdf.setFont("helvetica", "normal"); pdf.setFontSize(size); };
  const italic = (size) => { pdf.setFont("helvetica", "italic"); pdf.setFontSize(size); };
  return { heading, body, italic };
}

// Pregnancy "Midwife Handover" PDF — current week / due date / last-30-day
// symptom counts / medications + supplements / blank lines for questions.
function buildPregnancyPdf(snap, displayName) {
  const pdf = new jsPDF({ unit: "pt", format: "a4" });
  const margin = 48;
  const pageW = 595.28;
  const innerW = pageW - margin * 2;
  let y = margin;
  const { heading, body, italic } = pdfHelpers(pdf);

  const stage = snap.profile?.life_stage;
  const stageLabel = LIFE_STAGE_LABEL[stage] || "Pregnant";
  const due = snap.profile?.pregnancy_due_date;
  let currentWeek = null;
  if (due) {
    try {
      const d = new Date(due);
      const now = new Date();
      const weeksRemaining = Math.max(0, Math.round((d - now) / (1000 * 60 * 60 * 24 * 7)));
      currentWeek = Math.max(0, Math.min(40, 40 - weeksRemaining));
    } catch { /* ignore */ }
  }

  heading(20);
  pdf.text("Femwell — Midwife Handover", margin, y); y += 24;
  body(10.5);
  pdf.text(`Patient: ${displayName || "—"}`, margin, y); y += 14;
  pdf.text(`Stage: ${stageLabel}`, margin, y); y += 14;
  if (currentWeek != null) {
    pdf.text(`Current week: Week ${currentWeek} of 40`, margin, y); y += 14;
  }
  if (due) {
    pdf.text(`Due date: ${fmtDate(due)}`, margin, y); y += 14;
  } else {
    italic(10.5);
    pdf.text("Due date not yet set in Femwell.", margin, y); y += 14;
    body(10.5);
  }
  pdf.text(`Reporting window: ${fmtDate(snap.range.from)} → ${fmtDate(snap.range.to)}  (${snap.range.days} days)`, margin, y); y += 18;
  pdf.setDrawColor(168, 134, 75);
  pdf.setLineWidth(0.5);
  pdf.line(margin, y, pageW - margin, y); y += 18;

  // ── Symptoms last 30 days ────────────────────────────────────────────────
  heading(13);
  pdf.text("Symptoms logged (last 30 days)", margin, y); y += 18;
  body(11);

  const nauseaDays = countOf(snap.daily, "nausea", 1);
  const heavyNausea = countOf(snap.daily, "nausea", 3);
  const meanMood = avgOf(snap.daily, "mood");
  const sleepHours = avgOf(snap.daily, "sleep_hours");
  const lines = [
    `Days with nausea logged: ${nauseaDays}  ·  (≥3/5): ${heavyNausea}`,
    `Mean mood: ${meanMood ?? "—"} / 5`,
    `Mean sleep duration: ${sleepHours ?? "—"} hours/night`,
    `Total daily check-ins in window: ${snap.daily.length}`,
  ];
  for (const ln of lines) { pdf.text(ln, margin, y); y += 14; }
  if (snap.daily.length === 0) {
    italic(11);
    pdf.text("No daily check-ins in window.", margin, y); y += 14;
    body(11);
  }
  y += 8;

  // ── Medications / supplements ────────────────────────────────────────────
  heading(13);
  pdf.text("Medications / supplements", margin, y); y += 18;
  body(11);
  italic(10.5);
  pdf.text("Tick what applies and write in dose alongside:", margin, y); y += 14;
  body(11);
  for (const s of COMMON_SUPPLEMENTS) {
    pdf.text(`  ☐ ${s}  ____________________________`, margin, y); y += 14;
  }
  y += 8;

  // ── Questions for next appointment ───────────────────────────────────────
  heading(13);
  pdf.text("Questions for next appointment", margin, y); y += 18;
  body(11);
  for (let i = 0; i < 5; i++) {
    pdf.text(`${i + 1}.  ____________________________________________________`, margin, y); y += 18;
  }

  // Footer
  pdf.setDrawColor(168, 134, 75);
  pdf.line(margin, y, pageW - margin, y); y += 16;
  italic(9.5);
  pdf.text("Generated by Femwell · Not a medical record · For midwife conversation use", margin, y);
  body(9);
  pdf.text(`Generated ${fmtDate(new Date())}`, margin, y + 12);
  return pdf;
}

