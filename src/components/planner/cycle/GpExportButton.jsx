// ─────────────────────────────────────────────────────────────────────────────
// GpExportButton — STEP 7 of the Life Stage build.
//
// "Export for GP" one-tap PDF available on the Cycle tab for:
//   - Perimenopause / menopause (life_stage matches)
//   - Reproductive years
//   - Postpartum
//
// Builds a 1-page A4 PDF from data the user already has:
//   - User name + current life stage + date range
//   - Top symptoms by frequency (from DailyCheckins / MenopauseDailyLog)
//   - Cycle summary (last period start, average length, if relevant)
//   - Mean mood + mean sleep over the window
//   - Active HRT regimen (if logged)
//   - Footer disclaimer
//
// Footer line (per Halli's spec):
//   "Generated by Femwell · Not a medical record · For GP conversation use"
//
// Uses jsPDF (already in package.json) — no new dependency.
//
// This is a *separate* surface from DoctorReadyDiaryCard (which is the
// fuller NICE NG23 diary, mounted via the `doctor` cycle anchor). The GP
// export is the lighter, life-stage-aware variant we ship across more stages.
// ─────────────────────────────────────────────────────────────────────────────

