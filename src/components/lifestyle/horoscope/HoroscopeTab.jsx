function renderEm(text) {
  // Lightweight inline <em> renderer. Demo headlines use *word* in some
  // places — we accept either *word* or actual <em>word</em>. Strict HTML
  // escape on everything else.
  if (!text) return "";
  const escaped = String(text)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
  return escaped
    .replace(/&lt;em&gt;(.*?)&lt;\/em&gt;/g, '<em style="font-style:italic;">$1</em>')
    .replace(/\*(.+?)\*/g, '<em style="font-style:italic;">$1</em>');
}

