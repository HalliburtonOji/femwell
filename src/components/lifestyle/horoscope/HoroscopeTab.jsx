// HoroscopeTab — full rebuild per femwell_lifestyle_demo.html lines 783-970.
//
// Sections rendered in MP-Horo-A:
//   1. Hero            — date · kicker · headline · narrative · pills · moon
//   2. Triad           — sun / moon / rising (moon + rising locked until BT)
//   3. Today's weather — power / pressure / trouble energy cards
//   4. Cycle × Moon    — intersection narrative + paired ring visuals
//   5. This week       — 4 transit cards
//
// Compatibility + Ask-the-Stars land in MP-Horo-B and MP-Horo-C.
//
// Data flow:
//   AstroProfile  ← per-user birth data, written via BirthDataSheet
//   HoroscopeReading ← one row per user per day, generated by
//                       `generateHoroscopeReading` (orchestrator daily job)
//
// When today's reading hasn't generated yet we fall back to deterministic
// scaffold text from the sun sign + cycle phase so the page never reads
// "Check back soon" again.
// ─────────────────────────────────────────────────────────────────────────────

const TODAY_ISO = () => new Date().toISOString().split("T")[0];

export default function HoroscopeTab(props) {
  // Props are optional — when this component is mounted standalone we load
  // UserProfile / LifestyleProfile ourselves. If the parent already has them
  // loaded it can pass them down to avoid a duplicate fetch.
  const [user, setUser] = useState(null);
  const [astro, setAstro] = useState(null);     // AstroProfile row
  const [reading, setReading] = useState(null); // HoroscopeReading row
  const [userProfileLocal, setUserProfileLocal] = useState(props.userProfile || null);
  const [lifestyleProfileLocal, setLifestyleProfileLocal] = useState(props.lifestyleProfile || null);
  const [loading, setLoading] = useState(true);
  const [sheetOpen, setSheetOpen] = useState(false);
  const userProfile = props.userProfile || userProfileLocal;
  const lifestyleProfile = props.lifestyleProfile || lifestyleProfileLocal;

  // ── Initial load ─────────────────────────────────────────────────────────
  useEffect(() => {
    let cancelled = false;
    (async () => {
      setLoading(true);
      try {
        const u = await base44.auth.me().catch(() => null);
        if (cancelled) return;
        setUser(u);

        if (!u?.id) { setLoading(false); return; }

        const [aps, readings, profiles, lpRows] = await Promise.all([
          base44.entities.AstroProfile.filter({ user_id: u.id }, undefined, 1).catch(() => []),
          base44.entities.HoroscopeReading.filter(
            { user_id: u.id, reading_date: TODAY_ISO() },
            "-created_date",
            1,
          ).catch(() => []),
          props.userProfile
            ? Promise.resolve([props.userProfile])
            : base44.entities.UserProfile.filter({ user_id: u.id }, undefined, 1).catch(() => []),
          props.lifestyleProfile
            ? Promise.resolve([props.lifestyleProfile])
            : base44.entities.LifestyleProfile.filter({ user_id: u.id }, undefined, 1).catch(() => []),
        ]);
        if (cancelled) return;

        const ap = (aps && aps[0]) || null;
        setAstro(ap);
        setReading((readings && readings[0]) || null);
        if (!props.userProfile) setUserProfileLocal((profiles && profiles[0]) || null);
        if (!props.lifestyleProfile) setLifestyleProfileLocal((lpRows && lpRows[0]) || null);

        // Fire-and-forget kick if we have a chart but no reading for today —
        // the orchestrator picks this up nightly but the user shouldn't have
        // to wait if it's their first open of the day.
        if (ap && (!readings || !readings[0])) {
          base44.functions
            .invoke("generateHoroscopeReading", { user_id: u.id })
            .then((res) => {
              if (cancelled) return;
              const next = res?.data?.reading || res?.reading || null;
              if (next) setReading(next);
            })
            .catch(() => {});
        }
      } finally {
        if (!cancelled) setLoading(false);
      }
    })();
    return () => { cancelled = true; };
  }, []);

  // ── Derived chart facts (shown even when reading hasn't generated) ──────
  const chart = useMemo(() => deriveChart(astro, userProfile), [astro, userProfile]);
  const cyclePhase = useMemo(() => derivePhase(userProfile), [userProfile]);
  const moon = useMemo(() => getMoonPhase(new Date()), []);

  if (loading) {
    return <div style={loadingStyle}>Reading the sky…</div>;
  }

  // ── No chart yet — show onboarding card ──────────────────────────────────
  if (!astro) {
    return (
      <div>
        <OnboardingCard onOpen={() => setSheetOpen(true)} />
        <BirthDataSheet
          open={sheetOpen}
          onClose={() => setSheetOpen(false)}
          userId={user?.id}
          initial={null}
          onSaved={(saved) => setAstro(saved)}
        />
      </div>
    );
  }

  return (
    <div>
      <Hero
        chart={chart}
        moon={moon}
        astro={astro}
        reading={reading}
      />
      <Triad
        chart={chart}
        astro={astro}
        reading={reading}
        onAddBirthTime={() => setSheetOpen(true)}
      />
      <Weather reading={reading} chart={chart} />
      <CycleMoon
        cyclePhase={cyclePhase}
        moon={moon}
        reading={reading}
      />
      <Transits reading={reading} />
      <Compatibility userId={user?.id} chart={chart} />

      <BirthDataSheet
        open={sheetOpen}
        onClose={() => setSheetOpen(false)}
        userId={user?.id}
        initial={astro}
        onSaved={(saved) => setAstro(saved)}
      />
    </div>
  );
}

